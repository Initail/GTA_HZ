"""Side-effect-free city coordinates shared by data preparation and Blender.

No bpy import, scene initialization or asset writes. JSON is authoritative.
Geography/real building dimensions scale once; game-unit actors/interiors don't.
"""
from __future__ import annotations
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_city(city_id=None):
    if city_id is None:
        city_id = json.loads((ROOT / "config/active-city.json").read_text())["cityId"]
    if city_id not in ("shenzhen", "hangzhou"):
        raise ValueError(f"Unknown city: {city_id}")
    city = json.loads((ROOT / f"config/cities/{city_id}.json").read_text())
    geo = city["geography"]
    if geo["crs"] != "EPSG:4326":
        raise ValueError("Only WGS84 inputs are supported; convert other CRS first")
    if geo["projection"] == "wgs84-local-equirectangular":
        phi = math.radians(geo["originWGS84"][1])
        a, e2 = 6378137.0, 6.6943799901413165e-3
        den = 1 - e2 * math.sin(phi) ** 2
        geo["eastMetresPerDegree"] = math.pi / 180 * a / math.sqrt(den) * math.cos(phi)
        geo["northMetresPerDegree"] = math.pi / 180 * a * (1 - e2) / den ** 1.5
    return city


def project(lon, lat, city=None):
    geo = (city or load_city())["geography"]
    if not all(math.isfinite(v) for v in (lon, lat)) or not (-180 <= lon <= 180 and -90 <= lat <= 90):
        raise ValueError("Invalid WGS84 longitude/latitude")
    origin = geo["originWGS84"]
    return ((lon - origin[0]) * geo["eastMetresPerDegree"] * geo["scale"],
            (lat - origin[1]) * geo["northMetresPerDegree"] * geo["scale"])


def unproject(east, north, city=None):
    geo = (city or load_city())["geography"]
    return (geo["originWGS84"][0] + east / (geo["eastMetresPerDegree"] * geo["scale"]),
            geo["originWGS84"][1] + north / (geo["northMetresPerDegree"] * geo["scale"]))


def scale_metres(value, city=None):
    return value * (city or load_city())["geography"]["scale"]


def city_from_metadata(meta):
    """Existing Shenzhen metadata stays compatible; new cities must identify themselves."""
    if "cityId" in meta:
        city = load_city(meta["cityId"])
        geo = city["geography"]
        if meta["originWGS84"] != geo["originWGS84"] or meta["horizontalScale"] != geo["scale"]:
            raise ValueError("Asset metadata disagrees with city configuration")
        return city
    # Original interface had no cityId; its explicit legacy origin/scale remain authoritative.
    if not (113 <= meta["originWGS84"][0] <= 115 and 21 <= meta["originWGS84"][1] <= 24):
        raise ValueError("Non-Shenzhen assets require cityId; no silent legacy projection")
    city = load_city("shenzhen")
    city["geography"]["originWGS84"] = meta["originWGS84"]
    city["geography"]["scale"] = meta["horizontalScale"]
    return city


if __name__ == "__main__":
    import argparse
    import hashlib
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate-ts", action="store_true")
    args = parser.parse_args()
    profiles = {key: load_city(key) for key in ("shenzhen", "hangzhou")}
    if args.generate_ts:
        sources = [ROOT / "config/active-city.json", *sorted((ROOT / "config/cities").glob("*.json"))]
        digest = hashlib.sha256(b"".join(p.read_bytes() for p in sources)).hexdigest()
        active = json.loads(sources[0].read_text())["cityId"]
        text = "// Generated by scripts/city_config.py; edit config/cities/*.json.\n"
        text += f"export const CITY_CONFIG_SOURCE_SHA256={json.dumps(digest)};\n"
        text += "export const CITY_PROFILES=" + json.dumps(profiles, ensure_ascii=False, indent=2) + " as const;\n"
        text += f"export const ACTIVE_CITY_ID={json.dumps(active)} as const;\n"
        (ROOT / "src/city-profiles.generated.ts").write_text(text)
    else:
        print(json.dumps(profiles, ensure_ascii=False, indent=2))
